<section class="page container narrow prose">
  <p class="kicker">Privacy</p>
  <h1>What this site knows about you</h1>
  <p>Very little, on purpose.</p>
  <h2>Analytics</h2>
  <p>
    Page views are counted server-side with a self-hosted
    <a href="https://umami.is" rel="noopener">Umami</a> instance. It stores the page, the referrer, a
    coarse country, and a hashed identifier that resets daily. No cookies are set, nothing is shared with
    third parties, and there is no cross-site tracking.
  </p>
  <h2>Contact form</h2>
  <p>
    What you type in the contact form is e-mailed to me and kept in my mailbox. The proof-of-work
    check (<a href="https://capjs.js.org" rel="noopener">Cap</a>) runs in your browser and sends no
    personal data anywhere. Submissions are rate-limited per IP address; those addresses are not
    stored beyond a ten-minute window.
  </p>
  <h2>Dive log</h2>
  <p>
    The dive log is my own data. Dive buddies appear by first name only unless they have asked to be
    shown differently, and precise coordinates of sensitive sites are withheld.
  </p>
  <h2>Hosting</h2>
  <p>This site runs on a server in Germany (Hetzner). Server logs are rotated within days.</p>
</section>

